// Package bpf provides the loader for the Argus eBPF programs and maps.
//
// This file handles attaching the compiled TC (Traffic Control) eBPF programs
// to a network interface for both ingress and egress traffic. It also provides
// the map accessor used by the collector to read flow data.
//
// The //go:generate directive below is what drives `make generate`:
//   go generate ./internal/bpf/...
// will invoke bpf2go, which compiles network_stats.c and emits the typed
// Go accessor code (NetworkStatsObjects, NetworkStatsPrograms, etc.) into
// this same package directory.

// bpf2go embed directive — this tells bpf2go where to find the C source when
// invoked via `go generate`. The generated files (network_stats_bpfel.go etc.)
// will be placed in this directory with package name "bpf".

//go:generate go run github.com/cilium/ebpf/cmd/bpf2go -cc clang -no-strip -cflags "-O2 -g -Wall -Werror -I../../bpf/include" -target amd64 -go-package bpf NetworkStats ../../bpf/programs/network_stats.c

package bpf

import (
	"fmt"
	"net"
	"os"

	"github.com/cilium/ebpf"
	"github.com/cilium/ebpf/link"
	"github.com/sirupsen/logrus"
	"github.com/vishvananda/netlink"
)

// Objects holds the loaded eBPF programs and maps for the lifetime of the
// agent. It is returned by Load() and must be closed via Close() on shutdown
// to detach programs and free kernel resources.
type Objects struct {
	// bpfObjs is the typed struct generated by bpf2go. It embeds
	// NetworkStatsPrograms (the compiled TC programs) and
	// NetworkStatsMaps (the flow_map handle).
	bpfObjs NetworkStatsObjects

	// links holds the netlink/tc handles for the attached programs.
	// Closing these detaches the programs from the interface.
	ingressLink link.Link
	egressLink  link.Link

	// ifaceName is stored for logging and cleanup diagnostics.
	ifaceName string

	log *logrus.Logger
}

// FlowKey mirrors the C struct flow_key_t. bpf2go auto-generates a typed
// version (NetworkStatsFlowKeyT), but we define our own for clarity in the
// collector layer. They must be binary-identical.
//
// IMPORTANT: The Go compiler may add padding differently from C if you use
// plain types. Always verify with unsafe.Sizeof() == expected_size.
// Here we rely on the bpf2go-generated type which is derived from the C BTF,
// ensuring perfect alignment.
type FlowKey = NetworkStatsFlowKeyT

// FlowMetrics mirrors the C struct flow_metrics_t.
type FlowMetrics = NetworkStatsFlowMetricsT

// Load compiles (from embedded bytes), loads into the kernel, and attaches
// the TC eBPF programs to the named interface.
//
// Process:
//  1. ebpf.LoadCollectionSpec reads the embedded .o bytes (generated by bpf2go)
//  2. CollectionSpec.LoadAndAssign verifies and loads programs into the kernel
//  3. We attach tc_ingress and tc_egress to the interface's qdisc
//
// The caller must call objects.Close() when done (e.g., in a defer or signal
// handler) to cleanly detach the programs.
func Load(ifaceName string, log *logrus.Logger) (*Objects, error) {
	log.WithField("interface", ifaceName).Info("Loading eBPF programs")

	objs := &Objects{
		ifaceName: ifaceName,
		log:       log,
	}

	// Step 1: Load and verify the eBPF programs into the kernel.
	// LoadNetworkStatsObjects is generated by bpf2go; it calls
	// ebpf.LoadCollectionSpec on the embedded .o bytes, then calls
	// LoadAndAssign which runs the BPF verifier for each program.
	if err := LoadNetworkStatsObjects(&objs.bpfObjs, nil); err != nil {
		return nil, fmt.Errorf("loading eBPF objects: %w", err)
	}

	// Step 2: Look up the network interface by name.
	iface, err := net.InterfaceByName(ifaceName)
	if err != nil {
		objs.bpfObjs.Close()
		return nil, fmt.Errorf("finding interface %q: %w", ifaceName, err)
	}

	// Step 3: Ensure the interface has a clsact qdisc.
	// TC eBPF programs require a clsact (classless action) qdisc on the
	// interface. clsact provides the ingress and egress hooks that our
	// programs attach to. We add it idempotently (ignore EEXIST).
	if err := ensureClsactQdisc(iface.Index, log); err != nil {
		objs.bpfObjs.Close()
		return nil, fmt.Errorf("setting up clsact qdisc on %q: %w", ifaceName, err)
	}

	// Step 4: Attach tc_ingress program.
	objs.ingressLink, err = link.AttachTCX(link.TCXOptions{
		Interface: iface.Index,
		Program:   objs.bpfObjs.TcIngress,
		Attach:    ebpf.AttachTCXIngress,
	})
	if err != nil {
		objs.bpfObjs.Close()
		return nil, fmt.Errorf("attaching TC ingress program to %q: %w", ifaceName, err)
	}
	log.WithField("interface", ifaceName).Info("Attached TC ingress program")

	// Step 5: Attach tc_egress program.
	objs.egressLink, err = link.AttachTCX(link.TCXOptions{
		Interface: iface.Index,
		Program:   objs.bpfObjs.TcEgress,
		Attach:    ebpf.AttachTCXEgress,
	})
	if err != nil {
		// Clean up the ingress link we already attached.
		objs.ingressLink.Close()
		objs.bpfObjs.Close()
		return nil, fmt.Errorf("attaching TC egress program to %q: %w", ifaceName, err)
	}
	log.WithField("interface", ifaceName).Info("Attached TC egress program")

	return objs, nil
}

// FlowMap returns the raw *ebpf.Map for the flow_map.
// The collector uses this to iterate over all current flows.
func (o *Objects) FlowMap() *ebpf.Map {
	return o.bpfObjs.FlowMap
}

// Close detaches all eBPF programs from the interface and releases kernel
// resources. It is safe to call multiple times (subsequent calls are no-ops).
func (o *Objects) Close() {
	o.log.WithField("interface", o.ifaceName).Info("Detaching eBPF programs")

	if o.egressLink != nil {
		if err := o.egressLink.Close(); err != nil {
			o.log.WithError(err).Warn("Error closing egress TC link")
		}
	}
	if o.ingressLink != nil {
		if err := o.ingressLink.Close(); err != nil {
			o.log.WithError(err).Warn("Error closing ingress TC link")
		}
	}

	o.bpfObjs.Close()
}

// ensureClsactQdisc adds a clsact qdisc to the interface if one doesn't
// already exist. clsact is a special no-operation qdisc that provides the
// egress and ingress attachment hooks for TC eBPF classifiers.
//
// We use github.com/vishvananda/netlink for the Netlink operations instead
// of shelling out to the `tc` command, keeping Argus dependency-free at runtime.
func ensureClsactQdisc(ifIndex int, log *logrus.Logger) error {
	link, err := netlink.LinkByIndex(ifIndex)
	if err != nil {
		return fmt.Errorf("getting netlink for index %d: %w", ifIndex, err)
	}

	// List existing qdiscs and look for clsact.
	qdiscs, err := netlink.QdiscList(link)
	if err != nil {
		return fmt.Errorf("listing qdiscs: %w", err)
	}
	for _, q := range qdiscs {
		if q.Type() == "clsact" {
			log.WithField("interface", link.Attrs().Name).Debug("clsact qdisc already present")
			return nil
		}
	}

	// Add clsact qdisc.
	qdisc := &netlink.GenericQdisc{
		QdiscAttrs: netlink.QdiscAttrs{
			LinkIndex: ifIndex,
			// TC_H_ROOT and TC_H_CLSACT are defined in the kernel; netlink
			// uses the numeric values directly.
			Handle: netlink.MakeHandle(0xffff, 0),
			Parent: netlink.HANDLE_CLSACT,
		},
		QdiscType: "clsact",
	}
	if err := netlink.QdiscAdd(qdisc); err != nil {
		// EEXIST means another process raced us; that's fine.
		if !os.IsExist(err) {
			return fmt.Errorf("adding clsact qdisc: %w", err)
		}
	}
	log.WithField("interface", link.Attrs().Name).Debug("Added clsact qdisc")
	return nil
}
